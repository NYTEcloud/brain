// Bundles src/tenant.ts (the server's find, ranking, packing, facts and instant recall) into lib/server-engine.js.
// The only things replaced are the Workers runtime pieces: "cloudflare:workers" becomes a tiny DurableObject base
// class, timers are unref'd so a background flush never keeps a process alive, and WebSocketRequestResponsePair
// (used once in the constructor) is a plain class. Run from anywhere: node scripts/build-engine.mjs
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, "..");
const root = join(pkg, "..", "..");
const require = createRequire(join(root, "package.json"));
const { build } = require("esbuild");

const stub = {
  name: "workers-stub",
  setup(b) {
    b.onResolve({ filter: /^cloudflare:workers$/ }, () => ({ path: "cloudflare-workers-stub", namespace: "stub" }));
    b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({
      contents: "export class DurableObject { constructor(ctx, env) { this.ctx = ctx; this.env = env; } }",
      loader: "js",
    }));
  },
};

const banner = [
  "// Generated by scripts/build-engine.mjs from src/tenant.ts and its imports. Do not edit by hand.",
  "const setTimeout = (fn, ms) => { const t = globalThis.setTimeout(fn, ms); if (t && t.unref) t.unref(); return t; };",
  "class WebSocketRequestResponsePair { constructor(request, response) { this.request = request; this.response = response; } }",
].join("\n");

const out = join(pkg, "lib", "server-engine.js");
const r = await build({
  entryPoints: [join(here, "engine-entry.ts")],
  outfile: out,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node18",
  plugins: [stub],
  banner: { js: banner },
  legalComments: "none",
  logLevel: "warning",
});
const text = readFileSync(out, "utf8");
const m = /FIND_ENGINE = "([^"]+)"/.exec(text);
if (!m) throw new Error("FIND_ENGINE not found in the bundle");
writeFileSync(join(pkg, "lib", "engine-version.js"), `export const LOCAL_RANK_VERSION = ${JSON.stringify(m[1])};\n`);
console.log("built lib/server-engine.js (" + text.length + " bytes), engine " + m[1], r.errors.length ? "errors" : "ok");
