#!/usr/bin/env python3
"""Generate src/telonyte_brain/_vendor_client.py from client/brain.src.py.

The package answers from a local copy with the same engine, replica store, sync and WebSocket code as the
`brain` CLI, so that code is imported, not copied by hand. This script is the only place that touches it:
three small text changes, each asserted, and a header with the sha256 of the source.

  python3 build_vendor.py            write the vendored file
  python3 build_vendor.py --check    exit 1 when the committed file is not what the source produces
"""
import hashlib, pathlib, sys

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE.parent.parent / "client" / "brain.src.py"
OUT = HERE / "src" / "telonyte_brain" / "_vendor_client.py"

WS_GUID = '_WS_GUID = "258EAFA5-E914-47DA-95CA-C5AB0DC85B11"\n'
WS_UA_OLD = r'"User-Agent: brain-hosted/%s\r\n\r\n" % (prefix, path, hostport, nonce, key, VERSION)'
WS_UA_NEW = r'"%s\r\n\r\n" % (prefix, path, hostport, nonce, key, _ws_ua_lines())'
WS_UA_HOOK = (
    "\n# Hook added by build_vendor.py: the extra WebSocket handshake headers. The package replaces this per client\n"
    "# so the upgrade request carries its own User-Agent and X-Brain-Hyper.\n"
    "def _ws_ua_lines():\n"
    '    return "User-Agent: brain-hosted/%s" % VERSION\n'
)
MAIN_BLOCK = 'if __name__ == "__main__":\n    main(sys.argv[1:])\n'


def once(text, old, new, what):
    if text.count(old) != 1:
        sys.exit("build_vendor: cannot apply %s (found %d matches in %s)" % (what, text.count(old), SRC))
    return text.replace(old, new)


def build():
    raw = SRC.read_bytes()
    text = raw.decode("utf-8")
    if text.startswith("#!"):
        text = text.split("\n", 1)[1]
    text = once(text, WS_UA_OLD, WS_UA_NEW, "the WebSocket header hook")
    text = once(text, WS_GUID, WS_GUID + WS_UA_HOOK, "the WebSocket header hook definition")
    text = once(text, MAIN_BLOCK, "", "removal of the command line entry point")
    # the pinned sha256 of the engine archive the local search model installs (build-client.py does the same for the CLI)
    sys.path.insert(0, str(SRC.parent.parent / "scripts"))
    from embed_archive import embed_archive
    text = once(text, "@@EMBED_CODE_SHA@@", embed_archive(SRC.parent.parent, text, write=False)[0], "the engine archive sha256")
    head = ("# GENERATED by packages/pip-telonyte-brain/build_vendor.py from client/brain.src.py. Do not edit by hand.\n"
            "# source-sha256: %s\n"
            "# Importing this module has no side effects. Per-client paths and settings are set by telonyte_brain._local.\n"
            % hashlib.sha256(raw).hexdigest())
    return head + text


def main():
    out = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != out:
            sys.exit("build_vendor: %s is out of date; run build_vendor.py" % OUT)
        print("vendored client is up to date")
        return
    OUT.write_text(out, encoding="utf-8")
    print("wrote %s (%d bytes)" % (OUT, len(out.encode("utf-8"))))


if __name__ == "__main__":
    main()
